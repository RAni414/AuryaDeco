(function () {
  'use strict';
  var config = document.querySelector('[data-favorites-script]');
  if (!config) return;
  var KEY = 'auryadeco:favorites:v1', LIMIT = 200;
  var ids = [], storageOK = true, storageWarning = '', queue = Promise.resolve(), pending = new Set();
  var page = document.querySelector('[data-favorites-page]');
  var notice = document.querySelector('[data-favorites-notice]'), noticeTimer;
  var list = page && page.querySelector('[data-favorites-list]');
  function say(text) {
    if (!notice) return;
    clearTimeout(noticeTimer); notice.textContent = text; notice.hidden = false;
    noticeTimer = setTimeout(function () { notice.hidden = true; }, 4200);
  }
  function warning(text) {
    storageWarning = text;
    if (page) { var node = page.querySelector('[data-favorites-warning]'); node.textContent = text; node.hidden = !text; }
  }
  function normalize(value) {
    if (!Array.isArray(value)) throw new Error('Liste invalide');
    return Array.from(new Set(value.filter(function (id) { return Number.isInteger(id) && id > 0 && id <= 4294967295; }))).slice(0, LIMIT);
  }
  function temporary() {
    storageOK = false;
    warning('Le stockage de ce navigateur est bloqué. Vos favoris restent disponibles uniquement pendant cette page et seront perdus en quittant la page.');
  }
  function read() {
    if (!storageOK) return ids.slice();
    var raw;
    try { raw = window.localStorage.getItem(KEY); } catch (_) { temporary(); return ids.slice(); }
    if (raw === null) return [];
    try {
      if (raw.length > 12000) throw new Error('Liste trop volumineuse');
      var clean = normalize(JSON.parse(raw));
      if (JSON.stringify(clean) !== raw) {
        warning('Votre liste a été corrigée : les identifiants invalides ou en double ont été retirés.');
        write(clean);
      }
      return clean;
    } catch (_) {
      warning('Les favoris enregistrés étaient illisibles. Une nouvelle liste vide a été préparée.');
      write([]); return [];
    }
  }
  function write(value) {
    if (!storageOK) return;
    try { window.localStorage.setItem(KEY, JSON.stringify(value)); } catch (_) { temporary(); }
  }
  function sync() {
    document.querySelectorAll('[data-favorite-id]').forEach(function (button) {
      var id = Number(button.dataset.favoriteId), saved = ids.includes(id);
      button.hidden = false; button.disabled = pending.has(id);
      button.setAttribute('aria-pressed', saved ? 'true' : 'false');
      button.setAttribute('aria-label', saved ? 'Retirer des favoris' : 'Ajouter aux favoris');
      button.title = saved ? 'Retirer des favoris' : 'Ajouter aux favoris';
    });
    document.querySelectorAll('[data-favorites-count]').forEach(function (count) {
      if (count.textContent !== String(ids.length)) count.textContent = ids.length;
      count.hidden = ids.length === 0;
      var link = count.closest('a');
      if (link) link.setAttribute('aria-label', 'Mes favoris, ' + ids.length + ' produit' + (ids.length === 1 ? '' : 's'));
    });
  }
  async function validate(value, render) {
    var response = await fetch(config.dataset.endpoint, { method: 'POST', credentials: 'same-origin', cache: 'no-store',
      headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ ids: value, render: !!render, csrf: config.dataset.csrf }) });
    var data;
    try { data = await response.json(); } catch (_) { throw new Error('Les favoris sont temporairement indisponibles. Réessayez.'); }
    if (!response.ok) throw new Error(data.error || 'Les favoris sont indisponibles.');
    if (!Array.isArray(data.ids)) throw new Error('La liste de favoris reçue est invalide.');
    return data;
  }
  function setLoading(loading) {
    if (!page) return;
    page.querySelector('[data-favorites-loading]').hidden = !loading;
    list.setAttribute('aria-busy', loading ? 'true' : 'false');
  }
  function showError(error) {
    if (page) {
      var box = page.querySelector('[data-favorites-error]'); box.hidden = false; box.querySelector('p').textContent = error.message;
    } else say(error.message);
  }
  function render(data) {
    if (!page) return;
    page.querySelector('[data-favorites-error]').hidden = true;
    page.querySelector('[data-favorites-empty]').hidden = data.ids.length !== 0;
    // HTML is generated by our PHP template from escaped, current catalogue data.
    list.innerHTML = data.html || '';
    if (window.AuryaArt) window.AuryaArt.render(list);
    sync();
  }
  async function refresh() {
    ids = read(); sync(); setLoading(true);
    try {
      var source = ids.slice(), data = await validate(source, !!page);
      var latest = read();
      if (JSON.stringify(source) !== JSON.stringify(latest)) { ids = latest; return refresh(); }
      ids = normalize(data.ids);
      if (JSON.stringify(ids) !== JSON.stringify(source)) {
        write(ids); warning('Un ou plusieurs produits supprimés ou retirés du catalogue ont été enlevés de vos favoris.');
      }
      render(data); sync();
    } catch (error) { showError(error); }
    finally { setLoading(false); }
  }
  function enqueue(operation) { queue = queue.then(operation, operation).catch(showError); return queue; }
  async function toggle(button) {
    var id = Number(button.dataset.favoriteId);
    if (!Number.isInteger(id) || id < 1 || pending.has(id)) return;
    pending.add(id); sync();
    try {
      var source = read(), add = !source.includes(id);
      if (add && source.length >= LIMIT) { say('Vous pouvez conserver jusqu’à 200 favoris. Retirez un produit avant d’en ajouter un autre.'); return; }
      var proposed = add ? source.concat(id) : source.filter(function (value) { return value !== id; });
      var data = await validate(proposed, !!page);
      if (add && !data.ids.includes(id)) { say('Ce produit n’est plus proposé dans le catalogue.'); await refresh(); return; }
      // Preserve changes from other tabs that happened during the server check.
      var latest = read(), removed = proposed.filter(function (value) { return !data.ids.includes(value); });
      latest = latest.filter(function (value) { return !removed.includes(value) && (add || value !== id); });
      if (add && !latest.includes(id)) latest.push(id);
      ids = normalize(latest); write(ids); sync();
      if (page) {
        var focused = document.activeElement === button;
        if (JSON.stringify(ids) === JSON.stringify(data.ids)) render(data); else await refresh();
        if (focused) { var next = list.querySelector('[data-favorite-id]') || page.querySelector('[data-favorites-empty] a'); if (next) next.focus(); }
      }
      say((add ? 'Produit ajouté aux favoris.' : 'Produit retiré des favoris.') + (storageOK ? '' : ' Conservation temporaire sur cette page uniquement.'));
    } catch (error) { showError(error); }
    finally { pending.delete(id); sync(); }
  }
  document.addEventListener('click', function (event) {
    var button = event.target.closest('[data-favorite-id]');
    if (!button) return;
    event.preventDefault(); event.stopPropagation();
    enqueue(function () { return toggle(button); });
  });
  function enhanceAssistant() {
    document.querySelectorAll('[data-favorite-product]').forEach(function (card) {
      if (card.querySelector(':scope > [data-favorite-id]')) return;
      var button = document.createElement('button'); button.type = 'button'; button.className = 'fav-toggle';
      button.dataset.favoriteId = card.dataset.favoriteProduct;
      button.innerHTML = '<svg width="22" height="22" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" aria-hidden="true"><path d="M20.8 4.6a5.5 5.5 0 0 0-7.8 0L12 5.7l-1.1-1.1a5.5 5.5 0 0 0-7.8 7.8L12 21l8.8-8.6a5.5 5.5 0 0 0 0-7.8Z"/></svg>';
      card.prepend(button);
    });
    sync();
  }
  new MutationObserver(function (mutations) {
    if (mutations.some(function (m) { return Array.prototype.some.call(m.addedNodes, function (node) {
      return node.nodeType === 1 && (node.matches('[data-favorite-product],.pcard,.favorite-media') || node.querySelector('[data-favorite-product],.pcard,.favorite-media'));
    }); })) enhanceAssistant();
  }).observe(document.body, { childList: true, subtree: true });
  window.addEventListener('storage', function (event) { if (event.key === KEY || event.key === null) enqueue(refresh); });
  window.addEventListener('pageshow', function (event) { if (event.persisted) enqueue(refresh); });
  if (page) page.querySelector('[data-favorites-retry]').addEventListener('click', function () { enqueue(refresh); });
  ids = read(); enhanceAssistant();
  if (storageWarning && !page) say(storageWarning);
  enqueue(refresh);
})();
